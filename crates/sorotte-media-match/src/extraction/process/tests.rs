fn cancellation_while_consuming_output_cannot_return_a_successful_result() {
    let root = FixtureRoot::new();
    let cancelled = AtomicBool::new(false);
    let result = run_streaming(
        "ffprobe",
        root.command("duration", "launched"),
        Some(&cancelled),
        Deadline::after(Duration::from_secs(5)),
        PROBE_STDOUT_LIMIT,
        |_| {
            cancelled.store(true, Ordering::Release);
            Ok(())
        },
    );
    assert!(
        matches!(result, Err(MediaFingerprintError::Cancelled { .. })),
        "{result:?}"
    );
    // libtest can emit its banner before entering the fixture; the parent still
    // reaps the process even if the marker has not yet been created.
    if root.marker("launched").exists() {
        assert_stopped(&root.marker("launched"));
    }
}
